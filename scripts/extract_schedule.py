#!/usr/bin/env python3
"""Copy the build-schedule logic out of app/tracker.html into supabase/functions/_shared/schedule.js.

The connector has to list a home's tasks exactly the way the app does (company schedule, the home's options,
the company template, custom tasks). Rather than rewrite that logic, this pulls the app's own code, so the
connector can't drift from what people see on screen. It runs on every deploy; if a piece goes missing it stops.
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = (ROOT / "app" / "tracker.html").read_text()
OUT = ROOT / "supabase" / "functions" / "_shared" / "schedule.js"

# (anchor that starts the statement, exported name or None)
PIECES = [
    ("const ORD=", None), ("const LABEL=", None), ("const INSP=", None), ("const SCHEDULE=", None),
    ("const slug=", None), ("function applies(", None), ("SCHEDULE.forEach(", None),
    ("const OPTIONS=", None), ("const SUBBED=", None), ("const OPS_TASKS=", None),
    ("const TPL_DEF=", None), ("function tplParse(", None), ("const defNoMat=", None), ("function tplPhase(", None),
    ("const schedMemo=", None), ("function schedFor(", None),
    ("const pad=", None), ("const iso=", None), ("const parse=", None), ("const addDays=", None), ("const diff=", None),
    ("function optVal(", None), ("function phaseItems(", None), ("function phaseOn(", None), ("function phasesFor(", None),
    ("function allItems(", None), ("const S=", None), ("function subDone(", None), ("function isNA(", None),
    ("function isDone(", None), ("function parentOf(", None), ("function isLate(", None), ("function stats(", None),
    ("function homeDue(", None),
]


def statement(src, start):
    """Return the source of one top-level statement beginning at `start`."""
    i, depth, n = start, 0, len(src)
    is_fn = src.startswith("function", start)
    prev = ""  # last significant character, to tell a regex literal from division
    while i < n:
        c = src[i]
        if c in "\"'":
            j = i + 1
            while src[j] != c:
                j += 2 if src[j] == "\\" else 1
            i = j + 1; prev = c; continue
        if c == "`":
            i = template(src, i + 1); prev = "`"; continue
        if c == "/" and src[i + 1] == "/":
            i = src.index("\n", i); continue
        if c == "/" and src[i + 1] == "*":
            i = src.index("*/", i) + 2; continue
        if c == "/" and (prev == "" or prev in "(,=:[!&|?{};+-*%<>~^" or src[max(0, i - 6):i].endswith("return")):
            j, cls = i + 1, False
            while True:
                ch = src[j]
                if ch == "\\": j += 2; continue
                if ch == "[": cls = True
                elif ch == "]": cls = False
                elif ch == "/" and not cls: break
                j += 1
            j += 1
            while src[j].isalpha(): j += 1
            i = j; prev = "/"; continue
        if c in "([{": depth += 1
        elif c in ")]}":
            depth -= 1
            if depth == 0 and is_fn and c == "}":
                return src[start:i + 1]
        elif depth == 0 and (c == ";" or (c == "\n" and not is_fn)):
            return src[start:i + 1]
        if not c.isspace(): prev = c
        i += 1
    raise SystemExit("ran off the end")


def template(src, i):
    while True:
        c = src[i]
        if c == "\\": i += 2; continue
        if c == "`": return i + 1
        if c == "$" and src[i + 1] == "{":
            depth, i = 1, i + 2
            while depth:
                ch = src[i]
                if ch == "`": i = template(src, i + 1); continue
                if ch in "\"'":
                    j = i + 1
                    while src[j] != ch: j += 2 if src[j] == "\\" else 1
                    i = j + 1; continue
                if ch == "{": depth += 1
                elif ch == "}": depth -= 1
                i += 1
            continue
        i += 1


def find(anchor):
    hits = [m.start() for m in re.finditer(re.escape(anchor), SRC) if m.start() == 0 or SRC[m.start() - 1] in "\n;} \t"]
    if not hits:
        raise SystemExit(f"extract_schedule: couldn't find `{anchor}` in tracker.html. The app changed; update this script.")
    return hits[0]


parts = [statement(SRC, find(a)) for a, _ in PIECES]
body = "\n".join(parts)
OUT.write_text(
    "// GENERATED by scripts/extract_schedule.py from app/tracker.html. Don't edit by hand.\n"
    "// The app's own build-schedule logic, so the connector lists tasks exactly as the app shows them.\n"
    "export let TODAY = new Date().toISOString().slice(0, 10);\n"
    "export function setToday(d) { TODAY = d; }\n"
    + body
    + "\nexport { SCHEDULE, OPTIONS, LABEL, SUBBED, OPS_TASKS, schedFor, phasesFor, phaseItems, allItems, S, subDone, isNA, isDone, isLate, parentOf, stats, homeDue, optVal, slug, addDays, diff };\n"
)
print(f"schedule.js: {len(parts)} pieces, {len(body)} chars")
